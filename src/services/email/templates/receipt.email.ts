export function renderReceiptEmailText(data: ReceiptEmailData): string {
  return `Receipt #${data.receiptNumber} from ${data.gymName}
Status: PAID IN FULL

Hello ${data.customerName},

Thank you for your payment! Your membership details:
- Plan: ${data.planName}
- Total Paid: INR ${data.amount.toLocaleString("en-IN", { minimumFractionDigits: 2 })}
- Validity: ${data.validityDates}

Your official receipt PDF is attached to this email.
You can also download a copy anytime over the next 30 days using this link:
${data.signedDownloadUrl}

Thank you,
${data.gymName}
`;
}

