function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

export interface ReceiptEmailData {
  customerName: string;
  gymName: string;
  receiptNumber: string;
  planName: string;
  amount: number;
  validityDates: string;
  signedDownloadUrl: string;
}

